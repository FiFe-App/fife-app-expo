-- 4. A feed: "neked", "mind", "saját", "megoldott" + szöveges keresés
--
-- SECURITY DEFINER, mert a felhasználó bizniszeinek címkéit a buziness_tags / tags táblákból
-- olvassa, amikhez a hívónak nincs (és nem is szabad legyen) közvetlen SELECT-je. Ezért a
-- RLS-t itt kézzel ismételjük meg: auth.uid() nélkül nincs eredmény, a saját világ és a
-- tiltások ugyanúgy szűrnek, mint a policy.
--
-- p_scope:
--   'for_me'  nyitott, nem a sajátom, és a helyem a kérés körzetében van (vagy "bárhol");
--             az illeszkedők (a bizniszeim címkéi) előre
--   'all'     minden nyitott kérés a világomban
--   'mine'    az enyéim, nyitott és megoldott is
--   'solved'  a megoldott (archivált) kérések
-- p_query: szabad szöveg a címben, a leírásban és a címkékben (ILIKE, a joker karakterek
--          escape-elve). Bármelyik scope-pal használható.
--
-- Az "illeszkedés" két ágon megy: a kérés valamelyik címkéje megegyezik a bizniszeim valamelyik
-- címkéjével (normalize_tag-gel), VAGY a biznisz címkéje (min. 3 karakter) szerepel a kérés
-- címében / leírásában. Szemantikus (embedding) ág nincs: a kérés-címkék nincsenek a
-- tags szótárban, és a felhasználói szöveg nem megy ki az OpenAI-hoz.
-------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.requests_feed(
  p_scope  text DEFAULT 'all',
  p_query  text DEFAULT NULL,
  p_lat    double precision DEFAULT NULL,
  p_long   double precision DEFAULT NULL,
  p_skip   integer DEFAULT 0,
  p_take   integer DEFAULT 20
)
RETURNS TABLE(
  id            bigint,
  created_at    timestamptz,
  author        uuid,
  author_name   text,
  author_avatar text,
  title         text,
  description   text,
  tags          text[],
  images        text[],
  lat           double precision,
  long          double precision,
  radius        real,
  status        text,
  solved_at     timestamptz,
  distance      double precision,
  comment_count integer,
  is_match      boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $function$
  WITH me AS (
    SELECT auth.uid() AS uid,
           CASE WHEN p_lat IS NOT NULL AND p_long IS NOT NULL
                THEN st_point(p_long, p_lat)::geography END AS here,
           CASE WHEN btrim(COALESCE(p_query, '')) = '' THEN NULL
                ELSE '%' || replace(replace(replace(btrim(p_query), '\', '\\'), '%', '\%'), '_', '\_') || '%'
           END AS pattern
  ),
  my_tags AS (
    -- A bizniszeim címkéi, a szótár normalizált alakjában.
    SELECT DISTINCT tg.normalized AS n
    FROM public.buziness b
    JOIN public.buziness_tags bt ON bt.buziness_id = b.id
    JOIN public.tags tg ON tg.id = bt.tag_id
    WHERE b.author = (SELECT uid FROM me)
      AND char_length(tg.normalized) >= 3
  ),
  scored AS (
    SELECT
      r.*,
      p.full_name AS author_name,
      p.avatar_url AS author_avatar,
      CASE WHEN r.location IS NOT NULL AND (SELECT here FROM me) IS NOT NULL
           THEN st_distance(r.location, (SELECT here FROM me)) END AS dist,
      EXISTS (
        SELECT 1 FROM my_tags m
        WHERE m.n = ANY (ARRAY(SELECT public.normalize_tag(t) FROM unnest(r.tags) AS t))
           OR strpos(lower(r.title || ' ' || r.description), m.n) > 0
      ) AS matched
    FROM public.requests r
    JOIN public.profiles p ON p.id = r.author
    WHERE (SELECT uid FROM me) IS NOT NULL
      AND (r.author = (SELECT uid FROM me)
           OR (public.in_my_world(r.author) AND NOT public.is_blocked_by(r.author)))
      AND CASE p_scope
            WHEN 'for_me' THEN r.status = 'open'
                               AND r.author <> (SELECT uid FROM me)
                               AND (r.location IS NULL
                                    OR (SELECT here FROM me) IS NULL
                                    OR st_dwithin(r.location, (SELECT here FROM me), COALESCE(r.radius, 5000)))
            WHEN 'all'    THEN r.status = 'open'
            WHEN 'mine'   THEN r.author = (SELECT uid FROM me)
            WHEN 'solved' THEN r.status = 'solved'
            ELSE false
          END
      AND ((SELECT pattern FROM me) IS NULL
           OR r.title ILIKE (SELECT pattern FROM me)
           OR r.description ILIKE (SELECT pattern FROM me)
           OR array_to_string(r.tags, ' ') ILIKE (SELECT pattern FROM me))
  ),
  page AS (
    SELECT s.*
    FROM scored s
    ORDER BY (p_scope = 'for_me' AND s.matched) DESC,
             CASE WHEN p_scope = 'solved' THEN s.solved_at ELSE s.created_at END DESC,
             s.id DESC
    OFFSET GREATEST(COALESCE(p_skip, 0), 0)
    LIMIT  LEAST(GREATEST(COALESCE(p_take, 20), 1), 100)
  )
  SELECT
    pg.id, pg.created_at, pg.author, pg.author_name, pg.author_avatar,
    pg.title, pg.description, pg.tags, pg.images,
    st_y(pg.location::geometry), st_x(pg.location::geometry), pg.radius,
    pg.status, pg.solved_at, pg.dist,
    -- Csak a visszaadott oldalra számolva, nem az egész táblára.
    (SELECT count(*)::integer FROM public.comments c WHERE c.key = 'request/' || pg.id),
    pg.matched
  FROM page pg
  ORDER BY (p_scope = 'for_me' AND pg.matched) DESC,
           CASE WHEN p_scope = 'solved' THEN pg.solved_at ELSE pg.created_at END DESC,
           pg.id DESC
$function$;

REVOKE EXECUTE ON FUNCTION public.requests_feed(text, text, double precision, double precision, integer, integer)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.requests_feed(text, text, double precision, double precision, integer, integer)
  TO authenticated, service_role;

