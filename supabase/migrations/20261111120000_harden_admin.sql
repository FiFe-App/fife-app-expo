-- Hardening for the admin insights functions and the admin login.
--
-- 1. Empty search_path on the SECURITY DEFINER functions from
--    20260930120000_admin_insights.sql, like the rest of the newer code. Every
--    object they touch is already schema-qualified, so nothing resolves
--    differently; this only removes the possibility of a shadowing object in
--    `public` being picked up.
-- 2. admin_login_attempts: failed admin logins per IP, so the Netlify login
--    function can throttle password guessing. Service role only.

-------------------------------------------------------------------
-- 1. search_path
-------------------------------------------------------------------
ALTER FUNCTION public.admin_list_users(text, boolean, boolean, integer, integer) SET search_path = '';
ALTER FUNCTION public.admin_list_reports(uuid, text, integer, integer)          SET search_path = '';
ALTER FUNCTION public.admin_weekly_stats(timestamp with time zone, timestamp with time zone) SET search_path = '';
ALTER FUNCTION private.trigger_weekly_admin_report()                             SET search_path = '';

-------------------------------------------------------------------
-- 2. admin_login_attempts
-------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_login_attempts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip         text NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS admin_login_attempts_ip_created_idx
  ON public.admin_login_attempts (ip, created_at);

COMMENT ON TABLE public.admin_login_attempts
  IS 'Failed admin panel logins, one row per attempt. Written and read by the admin Netlify login function (service role).';

-- RLS on with no policies, and no grants: only the service role reaches it.
ALTER TABLE public.admin_login_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_login_attempts FROM anon, authenticated;
