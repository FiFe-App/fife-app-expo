-------------------------------------------------------------------
-- Autocomplete RPC. Mintája a meglévő get_popular_search_queries
-- (20260605000000_add_popular_queries_function.sql), amit a keresőmező használ.
-------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.search_tags(p_prefix text, p_limit integer DEFAULT 8)
RETURNS TABLE(name text, usage_count integer)
LANGUAGE sql
STABLE
SET search_path = ''
AS $$
  SELECT t.name, t.usage_count
  FROM public.tags t
  WHERE public.normalize_tag(p_prefix) <> ''
    AND t.normalized LIKE public.normalize_tag(p_prefix) || '%'
  ORDER BY t.usage_count DESC, t.normalized
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 8), 1), 20);
$$;

REVOKE EXECUTE ON FUNCTION public.search_tags(text, integer) FROM PUBLIC;
GRANT  EXECUTE ON FUNCTION public.search_tags(text, integer) TO anon, authenticated;

-------------------------------------------------------------------
-- Melyik címkéket szabad beágyazni.
--
-- A supabase/functions/fill-embeddings precedensét követjük: egy karbantartó job nem
-- lehet a hátsó ajtó, amin át mégis kimegy az OpenAI-hoz annak a szövege, aki az
-- "AI-s megtalálhatóság"-ot kikapcsolta. Egy címkét ezért csak akkor ágyazunk be, ha van
-- legalább egy olyan használója — biznisz szerzője vagy érdeklődési körként megadója —,
-- aki NEM kapcsolta ki a flaget.
--
-- A tisztán opt-outolt felhasználóktól származó címkék embedding nélkül maradnak; azok
-- továbbra is illeszthetők a szó szerinti ágon, csak szemantikusan nem.
--
-- A usage_count > 0 feltétel csak óvatosság: nulla számlálójú sor a trigger miatt nem
-- szokott létezni.
-------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.tags_pending_embedding(p_limit integer DEFAULT 200)
RETURNS TABLE(id bigint, name text)
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT t.id, t.name
  FROM public.tags t
  WHERE t.embedding IS NULL
    AND t.usage_count > 0
    AND (
      EXISTS (
        SELECT 1
        FROM public.buziness_tags bt
        JOIN public.buziness b ON b.id = bt.buziness_id
        LEFT JOIN public.user_settings s ON s.author = b.author
        WHERE bt.tag_id = t.id AND COALESCE(s.ai_enhance, false) = true
      )
      OR EXISTS (
        SELECT 1
        FROM public.interest_tags it
        LEFT JOIN public.user_settings s ON s.author = it.author
        WHERE it.tag_id = t.id AND COALESCE(s.ai_enhance, false) = true
      )
    )
  ORDER BY t.usage_count DESC, t.id
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 200), 1), 1000);
$$;

REVOKE EXECUTE ON FUNCTION public.tags_pending_embedding(integer) FROM PUBLIC;
GRANT  EXECUTE ON FUNCTION public.tags_pending_embedding(integer) TO service_role;
