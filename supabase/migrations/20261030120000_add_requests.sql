-- Kérések: a Közösség részben bárki kérhet valamit (kertészt, kölcsönadott fúrógépet,
-- bébiszittert), helyszínnel, címkékkel, szöveggel és képpel. Alá lehet kommentelni, a
-- létrehozója "megoldva"-nak jelölheti (ekkor archiválódik), és feljelenthető.
--
-- A kommentek NEM kapnak új táblát: a meglévő public.comments `key` oszlopa szabad szöveg
-- ("buziness/<id>" a bizniszeknél), ezért egy kérés kommentjei a "request/<id>" kulcs alatt
-- élnek, és a Comments komponens, a szerző-törlés, a tiltás és a feljelentés mind
-- változtatás nélkül működik rájuk.
--
-- MIÉRT "NEKED" RENDEZÉS ÉS NEM SZŰRÉS
-- A kérések személyre szabva jönnek: a felhasználó bizniszeinek címkéi és a helyzete szerint.
-- Ugyanazt az elvet követjük, mint az interest_buziness_feed (20260922140000): az illeszkedők
-- előre kerülnek, de a lista nem ürül ki, ha épp nincs illeszkedő, és a skip-alapú lapozás
-- egyetlen determinisztikus ORDER BY-on marad.

-------------------------------------------------------------------
-- 1. A tábla
-------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.requests (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  author      uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,

  title       text NOT NULL
              CONSTRAINT requests_title_length CHECK (char_length(btrim(title)) BETWEEN 3 AND 120),
  description text NOT NULL DEFAULT ''
              CONSTRAINT requests_description_length CHECK (char_length(description) <= 2000),

  -- Kulcsszavak, ugyanazzal a TagInput-tal vihetők fel, mint a biznisznél.
  tags        text[] NOT NULL DEFAULT '{}'
              CONSTRAINT requests_tags_count CHECK (cardinality(tags) <= 10),
  -- A requests bucketben lévő objektumok útvonalai (uid/<requestId>/<fájlnév>).
  images      text[] NOT NULL DEFAULT '{}'
              CONSTRAINT requests_images_count CHECK (cardinality(images) <= 4),

  -- NULL = "Bárhol": nincs földrajzi helyhez kötve, mindenkinek releváns.
  location    extensions.geography(Point, 4326),
  -- Méterben: mekkora körzetből várja a segítséget. Csak location mellett van értelme.
  radius      real CONSTRAINT requests_radius_range CHECK (radius IS NULL OR radius BETWEEN 100 AND 200000),

  -- 'solved' = megoldva, vagyis archivált: kikerül a feedekből, de az oldala olvasható marad.
  status      text NOT NULL DEFAULT 'open'
              CONSTRAINT requests_status_check CHECK (status IN ('open', 'solved')),
  solved_at   timestamptz,

  CONSTRAINT requests_solved_at_matches_status
    CHECK ((status = 'solved') = (solved_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS requests_open_created_idx
  ON public.requests (created_at DESC, id DESC) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS requests_solved_idx
  ON public.requests (solved_at DESC, id DESC) WHERE status = 'solved';
CREATE INDEX IF NOT EXISTS requests_author_idx
  ON public.requests (author, created_at DESC);
CREATE INDEX IF NOT EXISTS requests_location_idx
  ON public.requests USING gist (location);

-------------------------------------------------------------------
-- 2. Triggerek
--
-- BEFORE INSERT/UPDATE:
--  * solved_at-et a státusz vezérli, a kliens nem tud hamis időt írni;
--  * a szerző és a létrehozás ideje nem módosítható;
--  * egyszerre legfeljebb 10 nyitott kérés / felhasználó (spam ellen).
-------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.requests_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.author IS DISTINCT FROM OLD.author OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
      RAISE EXCEPTION 'A kérés szerzője és létrehozási ideje nem módosítható.'
        USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.status = 'solved' THEN
      NEW.solved_at := CASE WHEN OLD.status = 'solved' THEN OLD.solved_at ELSE now() END;
    ELSE
      NEW.solved_at := NULL;
    END IF;
  ELSE
    NEW.solved_at := CASE WHEN NEW.status = 'solved' THEN COALESCE(NEW.solved_at, now()) END;
  END IF;

  IF NEW.status = 'open'
     AND (TG_OP = 'INSERT' OR OLD.status <> 'open')
     AND (SELECT count(*) FROM public.requests r
          WHERE r.author = NEW.author AND r.status = 'open' AND r.id IS DISTINCT FROM NEW.id) >= 10
  THEN
    RAISE EXCEPTION 'Egyszerre legfeljebb 10 nyitott kérésed lehet. Jelöld megoldottnak a régebbieket.'
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS requests_before_write ON public.requests;
CREATE TRIGGER requests_before_write
  BEFORE INSERT OR UPDATE ON public.requests
  FOR EACH ROW EXECUTE FUNCTION public.requests_before_write();

-- A kérés törlésekor a kommentjei is mennek (a comments.key szabad szöveg, nincs rá FK).
CREATE OR REPLACE FUNCTION public.requests_delete_comments()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  DELETE FROM public.comments WHERE key = 'request/' || OLD.id;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS requests_delete_comments ON public.requests;
CREATE TRIGGER requests_delete_comments
  AFTER DELETE ON public.requests
  FOR EACH ROW EXECUTE FUNCTION public.requests_delete_comments();

-------------------------------------------------------------------
-- 3. RLS
--
-- Olvasni csak bejelentkezve lehet (anon semmit nem lát), a saját "világodból" (bad_boy
-- elkülönítés, mint a többi táblánál), és nem látod azokat, akikkel kölcsönösen tiltottátok
-- egymást. A megoldott kérés is olvasható marad (az oldala linkről megnyílik).
-------------------------------------------------------------------
ALTER TABLE public.requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "requests are readable in my world" ON public.requests;
CREATE POLICY "requests are readable in my world"
  ON public.requests AS PERMISSIVE FOR SELECT TO authenticated
  USING (
    author = (SELECT auth.uid())
    OR (public.in_my_world(author) AND NOT public.is_blocked_by(author))
  );

DROP POLICY IF EXISTS "requests are created by their author" ON public.requests;
CREATE POLICY "requests are created by their author"
  ON public.requests AS PERMISSIVE FOR INSERT TO authenticated
  WITH CHECK ((SELECT auth.uid()) = author);

DROP POLICY IF EXISTS "requests are edited by their author" ON public.requests;
CREATE POLICY "requests are edited by their author"
  ON public.requests AS PERMISSIVE FOR UPDATE TO authenticated
  USING ((SELECT auth.uid()) = author)
  WITH CHECK ((SELECT auth.uid()) = author);

DROP POLICY IF EXISTS "requests are deleted by their author" ON public.requests;
CREATE POLICY "requests are deleted by their author"
  ON public.requests AS PERMISSIVE FOR DELETE TO authenticated
  USING ((SELECT auth.uid()) = author);

REVOKE ALL ON public.requests FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.requests TO authenticated;
GRANT ALL ON public.requests TO service_role;

